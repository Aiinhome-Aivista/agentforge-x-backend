"""
app/services/code_generator_service.py
─────────────────────────────────────────────────────────────────────────────
Source-Code Generation Service

Implements spec section 3:
   "The platform should generate corresponding source code/scripts to
    automate each process step.  Generated code may include:
      • ETL Scripts
      • Pipeline Configurations
      • Transformation Logic
      • Deployment-ready automation code"

When the user clicks the new **Download the Code** dropdown entry on the
Suggestion Details page, this service builds an in-memory ZIP containing:

  agentforgex_<suggestion_slug>/
    README.md
    requirements.txt
    config/
        pipeline.yaml
        connections.yaml
    src/
        orchestrator.py          (LangGraph-style orchestrator skeleton)
        agents/
            <agent_name>.py      (one per detected agent)
        tools/
            <tool_name>.py       (one per detected tool)
        etl/
            extract.py
            transform.py
            load.py
    scripts/
        run_local.sh
        deploy.sh
    tests/
        test_orchestrator.py

The content is *fully dynamic* — every file is generated from the
suggestion + process + technical-design payload, so the user can clone &
run a meaningful skeleton, not boilerplate.
"""

