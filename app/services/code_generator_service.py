def _slugify(s: str) -> str:
    s = (s or "agent").lower()
    s = re.sub(r"[^a-z0-9]+", "_", s).strip("_")
    return s or "agent"


def _safe_name(s: str) -> str:
    return _slugify(s).replace("__", "_")


def _wrap(s: str) -> str:
    return textwrap.dedent(s).strip() + "\n"


# ─────────────────────────────────────────────────────────────────────────────
