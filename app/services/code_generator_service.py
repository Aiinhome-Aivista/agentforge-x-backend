def _orchestrator_steps_block(agents: List[Dict[str, Any]]) -> str:
    if not agents:
        return _wrap("            state['trace'].append('no_agents_configured')\n")
    lines = []
    for a in agents:
        name = _safe_name(a["name"])
        lines.append(f"            state = self.{name}.handle(state)")
        lines.append(f'            state["trace"].append("{name}")')
    return "\n".join(lines) + "\n"


def _class_name(s: str) -> str:
    parts = [p for p in re.split(r"[^A-Za-z0-9]+", s or "Agent") if p]
    return "".join(p.capitalize() for p in parts) or "Agent"


