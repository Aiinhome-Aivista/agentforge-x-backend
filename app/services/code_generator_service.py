# ─────────────────────────────────────────────────────────────────────────────
# Public entry point
# ─────────────────────────────────────────────────────────────────────────────
def build_code_zip(
    suggestion: Dict[str, Any],
    process: Dict[str, Any],
    steps: List[Dict[str, Any]],
    technical_design: Dict[str, Any],
    data_lineage: Optional[Dict[str, Any]] = None,
) -> bytes:
    """
    Returns the raw bytes of a ZIP file containing the scaffold.
    Safe to send directly from a Flask endpoint via send_file or Response.
    """
    suggestion_title = (
        suggestion.get("title") or suggestion.get("name") or "Agentic Automation"
    )
    process_title = (
        process.get("title") or process.get("name") or "Business Process"
    )

    # Pull agents + tools straight from the technical-design payload.
    # We prefer the top-level fields since Layer 3 (Agentic Core) is intentionally omitted from architecture_layers.
    agents_raw = technical_design.get("agents", [])
    tools_raw = technical_design.get("tools", [])

    agents: List[Dict[str, Any]] = []
    tools:  List[Dict[str, Any]] = []

    for a in agents_raw:
        if isinstance(a, dict):
            agents.append({
                "name":                  a.get("name", "Agent"),
                "role":                  a.get("role", ""),
                "responsibilities":      a.get("responsibilities") or [],
                "reasoning_framework":   a.get("reasoning_framework"),
                "model_tier":            a.get("model_tier"),
            })

    for t in tools_raw:
        if isinstance(t, dict):
            tools.append({
                "name":        t.get("tool_name") or t.get("name") or "Tool",
                "tool_name":   t.get("tool_name") or t.get("name") or "Tool",
                "purpose":     t.get("purpose", ""),
                "invoked_by":  t.get("invoked_by", ""),
            })

    # Deduplicate by name to avoid double files
    seen_a, uniq_a = set(), []
    for a in agents:
        k = _safe_name(a["name"])
        if k not in seen_a:
            uniq_a.append(a)
            seen_a.add(k)
    agents = uniq_a

    seen_t, uniq_t = set(), []
    for t in tools:
        k = _safe_name(t["name"])
        if k not in seen_t:
            uniq_t.append(t)
            seen_t.add(k)
    tools = uniq_t

    ctx = {
        "suggestion_id":    suggestion.get("_key") or suggestion.get("id") or "n/a",
        "suggestion_title": suggestion_title,
        "process_title":    process_title,
        "steps":            steps or [],
        "agents":           agents,
        "tools":            tools,
        "data_lineage":     data_lineage or {
            "data_source": {"name": "ADF (Azure Data Factory)", "type": "Data Integration Service"},
            "data_target": {"name": "Downstream Process System", "type": "Downstream System"},
        },
        "generated_at":     datetime.utcnow().isoformat(timespec="seconds") + "Z",
    }

    pkg_root = _safe_name(suggestion_title)
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, mode="w", compression=zipfile.ZIP_DEFLATED) as zf:
        zf.writestr(f"{pkg_root}/README.md",                _tpl_readme(ctx))
        zf.writestr(f"{pkg_root}/requirements.txt",          _tpl_requirements())
        zf.writestr(f"{pkg_root}/config/pipeline.yaml",      _tpl_pipeline_yaml(ctx))
        zf.writestr(f"{pkg_root}/config/connections.yaml",   _tpl_connections_yaml(ctx))
        zf.writestr(f"{pkg_root}/src/__init__.py",           "")
        zf.writestr(f"{pkg_root}/src/orchestrator.py",       _tpl_orchestrator(ctx))
        zf.writestr(f"{pkg_root}/src/agents/__init__.py",    "")
        for a in agents:
            zf.writestr(
                f"{pkg_root}/src/agents/{_safe_name(a['name'])}.py",
                _tpl_agent(a),
            )
        zf.writestr(f"{pkg_root}/src/tools/__init__.py",     "")
        for t in tools:
            zf.writestr(
                f"{pkg_root}/src/tools/{_safe_name(t['name'])}.py",
                _tpl_tool(t),
            )
        zf.writestr(f"{pkg_root}/src/etl/__init__.py",       "")
        zf.writestr(f"{pkg_root}/src/etl/extract.py",        _tpl_etl_extract())
        zf.writestr(f"{pkg_root}/src/etl/transform.py",      _tpl_etl_transform())
        zf.writestr(f"{pkg_root}/src/etl/load.py",           _tpl_etl_load())
        zf.writestr(f"{pkg_root}/scripts/run_local.sh",      _tpl_run_local_sh())
        zf.writestr(f"{pkg_root}/scripts/deploy.sh",         _tpl_deploy_sh())
        zf.writestr(f"{pkg_root}/tests/__init__.py",         "")
        zf.writestr(f"{pkg_root}/tests/test_orchestrator.py", _tpl_test_orch())

    return buf.getvalue()
